/**
 * Fontes bitmap autorais de Adventures of Pingo, desenhadas à mão.
 * Cada glifo é uma lista de linhas separadas por '/', com '#' = tinta e '.' = vazio.
 * Um prefixo "N:" diz em que linha da célula o desenho começa (0 = topo da célula).
 * As letras acentuadas são montadas no build: letra-base + sinal desenhado em `acentos`.
 */
export interface FonteSrc {
  nome: string;
  /** altura nominal da célula */
  altura: number;
  /** linhas extras acima da célula (acentos das maiúsculas) */
  topo: number;
  /** distância padrão entre linhas de texto */
  entrelinha: number;
  /** largura do espaço */
  espaco: number;
  glifos: Record<string, string>;
  acentos: Record<string, string>;
  /** letra composta → [base, acento] */
  compostos: Record<string, [string, string]>;
}

